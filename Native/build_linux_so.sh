#!/usr/bin/env bash
# Cross-compiles libaudiopluginresonanceaudio.so (Linux x86_64, glibc >= 2.17) with zig,
# WITHOUT the Embree-based reverb baking - same as the Windows build.
# Usage: build_linux_so.sh <resonance-audio repo root> <deps folder>
#   deps folder: nativeaudioplugins (Unity SDK header), ogg, vorbis checkouts, plus
#   core_sources.txt and exports.map from this folder.
set -euo pipefail
RA="$1"          # resonance-audio repo root (with per_source_reflections.patch applied)
WB="$2"          # deps folder
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$WB/out-linux"; OBJ="$WB/obj-linux"
mkdir -p "$OUT" "$OBJ"
ZIG="python3 -m ziglang"
TARGET="-target x86_64-linux-gnu.2.17"
COMMON="$TARGET -O2 -DNDEBUG -fPIC -msse -msse2 -msse3 -ffp-contract=off -DEIGEN_MPL2_ONLY -DPFFFT_STATIC_DEFINE"
INC="-I$RA -I$RA/resonance_audio -I$RA/third_party/eigen -I$RA/third_party/pffft \
     -I$RA/third_party/SADIE_hrtf_database/generated -I$WB/nativeaudioplugins/NativeCode \
     -I$WB/nativeaudioplugins -I$WB/gen -I$WB/ogg/include -I$WB/vorbis/include -I$WB/vorbis/lib"

compile() {  # $1 = source, $2 = language flags
  local src="$1"; local o="$OBJ/$(echo "$src" | tr '/.' '__').o"
  $ZIG ${CC_KIND} $COMMON $2 $INC -c "$src" -o "$o"
  echo "$o"
}
export -f compile; export ZIG COMMON INC OBJ CC_KIND

# ogg's config_types.h is normally generated by its configure step (Windows doesn't need it).
mkdir -p "$WB/gen/ogg"
cat > "$WB/gen/ogg/config_types.h" <<'H'
#ifndef __CONFIG_TYPES_H__
#define __CONFIG_TYPES_H__
#include <stdint.h>
typedef int16_t ogg_int16_t;
typedef uint16_t ogg_uint16_t;
typedef int32_t ogg_int32_t;
typedef uint32_t ogg_uint32_t;
typedef int64_t ogg_int64_t;
typedef uint64_t ogg_uint64_t;
#endif
H
cd "$RA"
SOURCES_CXX="$(cat "$HERE/core_sources.txt") \
  third_party/SADIE_hrtf_database/generated/hrtf_assets.cc \
  resonance_audio/utils/ogg_vorbis_recorder.cc \
  resonance_audio/utils/vorbis_stream_encoder.cc \
  platforms/unity/unity.cc \
  platforms/unity/unity_nativeaudioplugins.cc"
SOURCES_C="third_party/pffft/pffft.c third_party/pffft/pffft_common.c third_party/pffft/fftpack.c \
  $WB/ogg/src/bitwise.c $WB/ogg/src/framing.c \
  $(ls $WB/vorbis/lib/*.c | grep -v -E 'psytune|barkmel|tone|vorbisfile')"

CC_KIND="c++" printf '%s\n' $SOURCES_CXX | CC_KIND="c++" xargs -P 8 -I{} bash -c 'compile {} "-std=c++14"' > "$OBJ/cxx.list"
CC_KIND="cc"  printf '%s\n' $SOURCES_C   | CC_KIND="cc"  xargs -P 8 -I{} bash -c 'compile {} ""' > "$OBJ/c.list"

# Only the plugin's C entry points are exported; everything else (incl. the bundled
# ogg/vorbis) stays local so it can't clash with symbols already in the Unity process.
$ZIG c++ $TARGET -shared -O2 -fPIC -s \
  $(cat "$OBJ/cxx.list" "$OBJ/c.list") \
  -Wl,--version-script="$HERE/exports.map" -Wl,-soname,libaudiopluginresonanceaudio.so \
  -o "$OUT/libaudiopluginresonanceaudio.so"
ls -l "$OUT/libaudiopluginresonanceaudio.so"
